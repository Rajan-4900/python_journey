# NONE 
# none is a special constant in Python that represents the absence of a value or a null value. 
# It is often used to indicate that a variable has no value assigned to it or that a function does not return any value.

# Example:
def greet():
    print("Inside the Function : Hello, Python")

result = greet()  # This function does not return any value, so result will be None
print("not returning Any value: ", result)  # Output: None