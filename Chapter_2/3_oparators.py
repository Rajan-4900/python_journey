# arithmetic operators
x = 10
y = 5
print("Sum :", x + y)
print("Diff :", x - y)
print("Product :", x * y)
print("Division :", x / y)
print("Modulus :", x % y)
print("Exponent :", x ** y)

print()

# Comparison operators
print("Equal :", x == y)
print("Greater than :", x > y)
print("Less than :", x < y)
print("Greater than or equal :", x >= y)
print("Less than or equal :", x <= y)
print("Not equal :", x != y)

print()

